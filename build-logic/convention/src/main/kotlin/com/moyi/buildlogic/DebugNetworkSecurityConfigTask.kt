package com.moyi.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Writes `xml/network_security_config.xml` for the Android debug build: cleartext HTTP to
 * [hosts] and to nothing else. Generated rather than committed because the hosts are the
 * developer's own (the host of `moyi.apiBaseUrl`, and the LAN host the local backend signs
 * media URLs for), and they live in `local.properties`, never in the repository.
 *
 * Release builds have no such file and keep Android's default, which refuses cleartext.
 * A production host is refused here too, so a debug build can never send a token or an
 * entry to getmoyi.app over plain HTTP.
 */
@CacheableTask
abstract class DebugNetworkSecurityConfigTask : DefaultTask() {

    @get:Input
    abstract val hosts: ListProperty<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val checked = hosts.get().map { it.trim().lowercase() }.filter { it.isNotEmpty() }.distinct()
        checked.forEach { host ->
            if (isProductionHost(host)) {
                throw GradleException(
                    "Debug builds never allow cleartext to production ($host): real people's data " +
                        "lives there (CLAUDE.md, Configuration). Remove it from moyi.apiBaseUrl / moyi.devMediaHosts.",
                )
            }
            // A host name or an IPv4 address, nothing that could break out of the XML.
            if (!HOST.matches(host)) {
                throw GradleException("Not a host name or IPv4 address for the debug cleartext allowlist: '$host'")
            }
        }
        val domains = checked.joinToString("\n") { "        <domain includeSubdomains=\"false\">$it</domain>" }
        val xml = outputDir.get().dir("xml").asFile.apply { mkdirs() }.resolve("network_security_config.xml")
        xml.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by :androidApp:generateDebugNetworkSecurityConfig. Do not edit.
            |     Debug builds only: cleartext HTTP to the local backend and nothing else. -->
            |<network-security-config>
            |    <domain-config cleartextTrafficPermitted="true">
            |$domains
            |    </domain-config>
            |</network-security-config>
            |""".trimMargin(),
        )
    }

    private companion object {
        val HOST = Regex("^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)*$")
    }
}

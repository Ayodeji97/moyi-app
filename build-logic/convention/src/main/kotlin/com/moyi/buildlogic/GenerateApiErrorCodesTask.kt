package com.moyi.buildlogic

import groovy.json.JsonSlurper
import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Writes `ApiErrorCode.kt`, an enum of every `ProblemDetail.code` value in the
 * contract plus `Unknown`, into a framework-free module.
 *
 * Why generate it: the app switches on these codes in domain and feature code,
 * which may not see the generated network client. Generating the enum from the
 * same contract keeps it exhaustive with no hand-maintenance; a new server code
 * appears here on the next `syncContract`. A test in `:shared:data:network`
 * checks it against the OpenAPI generator's own `ProblemDetail.Code`.
 */
@CacheableTask
abstract class GenerateApiErrorCodesTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val contract: RegularFileProperty

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        @Suppress("UNCHECKED_CAST")
        val root = JsonSlurper().parse(contract.get().asFile) as Map<String, Any?>
        val codes = root.path("components", "schemas", "ProblemDetail", "properties", "code", "enum")
            as? List<*>
            ?: throw GradleException("contracts/openapi.json has no components.schemas.ProblemDetail.properties.code.enum")
        val names = codes.map { it.toString() }
        names.firstOrNull { !it.matches(Regex("[A-Z][A-Z0-9_]*")) }?.let {
            throw GradleException("ProblemDetail code '$it' is not a SCREAMING_SNAKE_CASE identifier")
        }

        val pkg = packageName.get()
        val dir = outputDir.get().asFile.resolve(pkg.replace('.', '/'))
        dir.deleteRecursively()
        dir.mkdirs()
        dir.resolve("ApiErrorCode.kt").writeText(
            buildString {
                appendLine("// Generated by the generateApiErrorCodes task from contracts/openapi.json. Do not edit.")
                appendLine("package $pkg")
                appendLine()
                appendLine("/**")
                appendLine(" * Every `code` a backend problem response can carry (doc 06 §2), in contract order,")
                appendLine(" * plus [Unknown] for a code this build has not heard of yet.")
                appendLine(" */")
                appendLine("enum class ApiErrorCode {")
                names.forEach { appendLine("    $it,") }
                appendLine("    Unknown,")
                appendLine("}")
            },
        )
    }

    private fun Map<String, Any?>.path(vararg keys: String): Any? =
        keys.fold(this as Any?) { node, key -> (node as? Map<*, *>)?.get(key) }
}
